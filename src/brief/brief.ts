/**
 * Country Macro Brief (PRD §10.2): a one-page Markdown document assembled
 * entirely from deterministic outputs. Exportable as .md or printed to PDF.
 */
import { getCountry } from '../shared/countries';
import type { CountryCode, IndicatorKey, IndicatorSnapshot } from '../shared/types';
import type { ProcessedArticle } from '../nlp/analyze';
import type { DocumentAnalysis } from '../nlp/document';
import { EVENT_LABELS, type MacroEvent } from '../nlp/events';
import type { ForecastResult } from '../forecast/model';
import type { RiskScore } from '../analytics/risk';
import { DISCLAIMER } from '../shared/disclaimer';

export interface BriefInputs {
  code: CountryCode;
  benchmark?: CountryCode;
  snapshot: IndicatorSnapshot;
  events: readonly MacroEvent[];
  articles: readonly ProcessedArticle[];
  forecast: ForecastResult;
  risk: RiskScore;
  document?: DocumentAnalysis;
  narrative: string;
  now?: Date;
}

const ROWS: [IndicatorKey, string][] = [
  ['gdpGrowth', 'GDP growth'],
  ['cpi', 'CPI inflation'],
  ['policyRate', 'Policy rate'],
  ['unemployment', 'Unemployment'],
  ['fx', 'Exchange rate'],
  ['tradeBalance', 'Trade balance'],
];

function cell(snapshot: IndicatorSnapshot, code: CountryCode, key: IndicatorKey): string {
  const s = snapshot.countries[code]?.series[key];
  const p = s?.points.at(-1);
  return p
    ? `${p[1].toLocaleString('en-US', { maximumFractionDigits: 2 })} ${s!.unit} (${p[0]})`
    : '—';
}

const escapeMd = (s: string) => s.replace(/([|*_[\]])/g, '\\$1');

export function buildCountryBrief(input: BriefInputs): string {
  const c = getCountry(input.code);
  const bench = input.benchmark ? getCountry(input.benchmark) : undefined;
  const date = (input.now ?? new Date()).toISOString().slice(0, 10);
  const events = input.events.filter((e) => e.country === input.code).slice(0, 5);
  const articles = input.articles
    .filter((a) => a.country === input.code && a.weight > 0)
    .slice(0, 3);
  const f = input.forecast;

  const lines = [
    `# ${c.name} — Country Macro Brief`,
    `*Generated by FedLens on ${date} · data snapshot ${input.snapshot.generatedAt.slice(0, 10)}*`,
    '',
    '## Summary',
    input.narrative,
    '',
    '## Macro snapshot',
    bench ? `| Indicator | ${c.name} | ${bench.name} |` : `| Indicator | ${c.name} |`,
    bench ? '|---|---|---|' : '|---|---|',
    ...ROWS.map(([key, label]) =>
      bench
        ? `| ${label} | ${cell(input.snapshot, c.code, key)} | ${cell(input.snapshot, bench.code, key)} |`
        : `| ${label} | ${cell(input.snapshot, c.code, key)} |`,
    ),
    '',
    '## Policy outlook',
    `- **Forecast:** ${f.direction} — P(tighten) ${Math.round(f.pTighten * 100)}%, P(ease) ${Math.round(f.pEase * 100)}% · confidence ${f.confidence}`,
    `- **Policy risk score:** ${input.risk.score}/100 (${input.risk.level})`,
    input.document
      ? `- **${c.centralBankShort} stance:** ${input.document.stance.label} — from "${escapeMd(input.document.title)}" (${input.document.analyzedAt.slice(0, 10)})`
      : `- **${c.centralBankShort} stance:** no document analysed yet`,
    '',
    '### Forecast inputs',
    '| Input | Weight | Points | Detail |',
    '|---|---|---|---|',
    ...f.inputs.map(
      (i) =>
        `| ${i.label} | ${i.weight}% | ${i.available ? (i.points > 0 ? '+' : '') + i.points : 'n/a'} | ${escapeMd(i.detail)} |`,
    ),
    '',
    '## Recent events',
    ...(events.length
      ? events.map(
          (e) =>
            `- ${e.date} · **${EVENT_LABELS[e.type]}** · ${escapeMd(e.headline)} (${e.confidence})`,
        )
      : ['- No events detected in the current window.']),
    '',
    '## Recent coverage',
    ...(articles.length
      ? articles.map(
          (a) =>
            `- [${escapeMd(a.title)}](${a.link}) — ${escapeMd(a.source)}, ${a.publishedAt.slice(0, 10)} · ${a.analysis.sentiment.label}`,
        )
      : ['- No recent credible coverage in the archive.']),
    '',
    '---',
    `*${DISCLAIMER}*`,
  ];
  return lines.join('\n');
}
